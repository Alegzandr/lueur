<script lang="ts">
  import { onMount } from "svelte";
  import {
    app,
    addDevices,
    assignDevice,
    bindingFor,
    closeTuya,
    deviceName,
    endpointOf,
    endpointOfDevice,
    identify,
    openTuya,
    pair,
    renameLight,
    scan,
    signInTuya,
    unassign,
  } from "../state.svelte";
  import { t, tn } from "../i18n";
  import type { DiscoveredDevice, Family } from "../types";
  import Icon from "../ui/Icon.svelte";

  // First visit: look straight away rather than greeting with an empty list.
  onMount(() => {
    if (!app.hasScanned) void scan();
  });

  const lights = $derived(app.config.room.lights);
  const unboundLights = $derived(lights.filter((l) => !bindingFor(l.id)));
  // Bulbs already bound are listed under "In the room"; only show the rest here.
  const unbound = $derived(app.discovered.filter((d) => !app.config.bindings.some((b) => b.device_id === d.id)));
  const fresh = $derived(unbound.filter((d) => d.paired));

  // Brand names, the same in every language.
  const FAMILY: Record<Family, string> = {
    yeelight: "Yeelight",
    wiz: "WiZ",
    lifx: "LIFX",
    govee: "Govee",
    hue: "Philips Hue",
    nanoleaf: "Nanoleaf",
    tuya: "Smart Life",
  };

  let userCode = $state("");

  /** Only Yeelight reports what it can do; every other family can stream. */
  function supportsMusic(d: DiscoveredDevice): boolean {
    if (d.kind.family !== "yeelight") return true;
    return d.support.includes("set_music") && d.support.includes("set_rgb");
  }

  function onAssign(d: DiscoveredDevice, e: Event & { currentTarget: HTMLSelectElement }) {
    const id = e.currentTarget.value;
    e.currentTarget.value = "";
    if (id === "__new") addDevices([d]);
    else if (id) assignDevice(id, d);
  }
</script>

<div class="page">
  <header class="page-head">
    <h1 class="page-title">{t("nav_bulbs")}</h1>
    <div class="actions">
      {#if fresh.length > 1 && unboundLights.length === 0}
        <button class="btn" onclick={() => addDevices(fresh)}>{t("add_all")}</button>
      {/if}
      <button class="btn" title={t("tuya_open_tip")} onclick={openTuya} disabled={app.tuya !== null}>
        {t("tuya_open")}
      </button>
      <button class="btn" class:primary={!app.hasScanned} onclick={() => scan()} disabled={app.scanning}>
        {#if app.scanning}<span class="spinner" aria-hidden="true"></span>{/if}
        {app.scanning ? t("searching") : app.hasScanned ? t("search_again") : t("search")}
      </button>
    </div>
  </header>

  {#if app.tuya}
    <section class="group">
      <div class="group-head">
        <h2 class="group-title">{t("tuya_title")}</h2>
      </div>
      <div class="card tuya">
        {#if app.tuya.step === "qr" && app.tuya.login}
          <!-- Generated by the backend from a validated token, never fetched. -->
          <div class="qr" role="img" aria-label="QR code">{@html app.tuya.login.svg}</div>
          <div class="tuya-text">
            <p>{t("tuya_scan")}</p>
            <p class="note waiting"><span class="spinner" aria-hidden="true"></span> {t("tuya_waiting")}</p>
            <div>
              <button class="btn plain sm" onclick={closeTuya}>{t("tuya_cancel")}</button>
            </div>
          </div>
        {:else}
          <form
            class="tuya-text"
            onsubmit={(e) => {
              e.preventDefault();
              void signInTuya(userCode);
            }}
          >
            <label class="code">
              <span>{t("tuya_code")}</span>
              <input type="text" bind:value={userCode} spellcheck="false" autocomplete="off" maxlength="64" />
            </label>
            <p class="note">{t("tuya_code_help")}</p>
            <div class="actions">
              <button class="btn plain" type="button" onclick={closeTuya}>{t("tuya_cancel")}</button>
              <button
                class="btn primary"
                type="submit"
                disabled={app.tuya.step === "starting" || !/^[A-Za-z0-9]{4,64}$/.test(userCode.trim())}
              >
                {#if app.tuya.step === "starting"}<span class="spinner" aria-hidden="true"></span>{/if}
                {t("tuya_continue")}
              </button>
            </div>
          </form>
        {/if}
      </div>
    </section>
  {/if}

  {#if unbound.length > 0 || lights.length === 0}
  <section class="group">
    <div class="group-head">
      <h2 class="group-title">{t("on_network")}</h2>
      {#if app.hasScanned && !app.scanning}
        <span class="note">{tn("n_found", unbound.length)}</span>
      {/if}
    </div>

    <div class="card rows">
      {#if unbound.length === 0}
        <div class="empty">
          {#if app.scanning}
            <p>{t("listening")}</p>
          {:else if app.hasScanned}
            <p class="empty-title">{t("none_title")}</p>
          {:else}
            <p class="empty-title">{t("first_title")}</p>
            <p>{t("first_text")}</p>
          {/if}
        </div>
      {:else}
        {#each unbound as d (d.id)}
          <div class="device">
            <div class="device-text">
              <div class="device-name">{deviceName(d)}</div>
              <div class="device-meta num">
                {FAMILY[d.kind.family]} {d.model || ""} · {d.ip}{#if !d.paired}<span class="warn"
                    >, {t("needs_pairing")}</span
                  >{:else if !supportsMusic(d)}<span class="warn">, {t("no_music")}</span>{/if}
              </div>
            </div>
            {#if d.paired}
              <button class="btn plain sm" title={t("identify_tip")} onclick={() => identify(endpointOfDevice(d))}>
                {t("identify")}
              </button>
            {/if}
            {#if !d.paired}
              <button class="btn sm" title={t("pair_tip")} onclick={() => pair(d)} disabled={app.pairing !== null}>
                {#if app.pairing === d.id}<span class="spinner" aria-hidden="true"></span>{/if}
                {app.pairing === d.id ? t("pairing") : t("pair")}
              </button>
            {:else if unboundLights.length > 0}
              <select class="assign" aria-label="{deviceName(d)}: {t('use_for')}" onchange={(e) => onAssign(d, e)}>
                <option value="" selected disabled>{t("use_for")}</option>
                {#each unboundLights as l (l.id)}
                  <option value={l.id}>{l.name}</option>
                {/each}
                <option value="__new">{t("new_light")}</option>
              </select>
            {:else}
              <button class="btn sm" onclick={() => addDevices([d])}>{t("add")}</button>
            {/if}
          </div>
        {/each}
      {/if}
    </div>
  </section>
  {/if}

  {#if lights.length > 0}
    <section class="group">
      <div class="group-head">
        <h2 class="group-title">{t("in_room")}</h2>
        <button class="btn plain sm" onclick={() => (app.view = "room")}>{t("step2_btn")}</button>
      </div>
      <div class="card rows">
        {#each lights as l (l.id)}
          {@const b = bindingFor(l.id)}
          <div class="device">
            <input
              class="rename"
              type="text"
              value={l.name}
              spellcheck="false"
              aria-label={t("light_name")}
              oninput={(e) => renameLight(l.id, e.currentTarget.value)}
            />
            <div class="device-meta num grow">
              {#if b}{b.ip}{:else}<span class="warn">{t("pick_above")}</span>{/if}
            </div>
            {#if b}
              <button class="btn plain sm" title={t("identify_tip")} onclick={() => identify(endpointOf(b))}>
                {t("identify")}
              </button>
              <button class="btn plain sm" title={t("unassign_tip")} onclick={() => unassign(l.id)}>
                {t("unassign")}
              </button>
            {/if}
          </div>
        {/each}
      </div>
    </section>
  {/if}

  <section class="group">
    <details class="card tips" open={app.hasScanned && app.discovered.length === 0}>
      <summary>
        <Icon name="chevron" size={14} />
        <span>{t("tips_title")}</span>
      </summary>
      <ol>
        <li>{t("tip_1")}</li>
        <li>{t("tip_2")}</li>
        <li>{t("tip_3")}</li>
        <li>{t("tip_4")}</li>
        <li>{t("tip_5")}</li>
      </ol>
    </details>
  </section>
</div>

